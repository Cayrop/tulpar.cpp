#!/usr/bin/env bash
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
PIDFILE="${ROOT}/ops/run/llama-server.pid"
PROD_BIN="${ROOT}/build-p3/bin/llama-server"
MODEL="/home/gencer/models/qwen-v2/Qwen3.8-27B-UD-Q2_K_XL.gguf"
EXPECTED_PORT="8080"
EXPECTED_HOST="0.0.0.0"
MANIFEST_DIR="${ROOT}/ops/manifest"
CAPTURE_FILE="${MANIFEST_DIR}/current_prod_capture.txt"

ALLOW_CAPTURE="${ALLOW_CAPTURE_CURRENT_PROD_PID:-NO}"

usage() {
    echo "Usage: $0"
    echo "Capture current production llama-server PID into pidfile."
    echo ""
    echo "Requires ALLOW_CAPTURE_CURRENT_PROD_PID=YES."
    echo "This script does NOT send any signals to any process."
    echo ""
    echo "Steps:"
    echo "  1. Discover llama-server candidates via pgrep"
    echo "  2. Validate exe path, cmdline, model, port"
    echo "  3. Write PID to pidfile and manifest"
}

if [[ "$ALLOW_CAPTURE" != "YES" ]]; then
    echo "ERROR: ALLOW_CAPTURE_CURRENT_PROD_PID is not set to YES."
    echo "Set ALLOW_CAPTURE_CURRENT_PROD_PID=YES to enable PID capture."
    exit 1
fi

echo "[ALLOW_CAPTURE_CURRENT_PROD_PID=YES] Proceeding with PID capture."

echo "--- Discovery ---"
CANDIDATES=$(pgrep -x llama-server 2>/dev/null || true)
if [[ -z "$CANDIDATES" ]]; then
    echo "No llama-server processes found via pgrep -x."
    echo "CURRENT_PROD_PID_CAPTURE = FAILED"
    echo "REASON = no llama-server process found"
    exit 1
fi

CANDIDATE_COUNT=$(echo "$CANDIDATES" | wc -l)
if [[ "$CANDIDATE_COUNT" -gt 1 ]]; then
    echo "ERROR: Multiple llama-server candidates found:"
    echo "$CANDIDATES"
    echo "Aborting: exactly one production process expected."
    echo "CURRENT_PROD_PID_CAPTURE = FAILED"
    echo "REASON = multiple llama-server candidates ($CANDIDATE_COUNT found)"
    exit 1
fi

CANDIDATE_PID=$(echo "$CANDIDATES" | head -1 | awk '{print $1}')
echo "Single candidate found: PID $CANDIDATE_PID"

echo "--- Validation ---"
VALIDATION_FAILED=false

EXE_PATH=""
if [[ -d "/proc/$CANDIDATE_PID" ]]; then
    EXE_PATH=$(readlink /proc/$CANDIDATE_PID/exe 2>/dev/null || echo "")
    CMDLINE=$(cat /proc/$CANDIDATE_PID/cmdline 2>/dev/null | tr '\0' ' ' || echo "")
else
    echo "ERROR: /proc/$CANDIDATE_PID not accessible"
    VALIDATION_FAILED=true
fi

if [[ -z "$EXE_PATH" ]]; then
    echo "ERROR: Cannot read /proc/$CANDIDATE_PID/exe"
    VALIDATION_FAILED=true
elif [[ "$EXE_PATH" != *"$PROD_BIN" ]]; then
    echo "ERROR: exe path does not match production binary"
    echo "  expected: $PROD_BIN"
    echo "  actual:   $EXE_PATH"
    VALIDATION_FAILED=true
else
    echo "exe path match: YES ($EXE_PATH)"
fi

if [[ -z "$CMDLINE" ]]; then
    echo "ERROR: Cannot read /proc/$CANDIDATE_PID/cmdline"
    VALIDATION_FAILED=true
elif [[ "$CMDLINE" != *"$MODEL"* ]]; then
    echo "ERROR: cmdline does not contain expected model path"
    echo "  expected model: $MODEL"
    echo "  cmdline: $CMDLINE"
    VALIDATION_FAILED=true
else
    echo "cmdline model path match: YES"
fi

if [[ "$CMDLINE" == *"--port ${EXPECTED_PORT}"* ]] || [[ "$CMDLINE" == *"-p ${EXPECTED_PORT}"* ]]; then
    echo "cmdline port match: YES ($EXPECTED_PORT)"
else
    echo "WARNING: cmdline port match not confirmed (port $EXPECTED_PORT)"
fi

if [[ "$CMDLINE" == *"--host ${EXPECTED_HOST}"* ]]; then
    echo "cmdline host match: YES ($EXPECTED_HOST)"
else
    echo "WARNING: cmdline host match not confirmed (host $EXPECTED_HOST)"
fi

if [[ "$VALIDATION_FAILED" == "true" ]]; then
    echo ""
    echo "VALIDATION FAILED. Aborting. No pidfile written."
    echo "CURRENT_PROD_PID_CAPTURE = FAILED"
    echo "REASON = validation failed (exe/cmdline/model/port check)"
    exit 1
fi

echo ""
echo "--- Capture ---"
mkdir -p "${ROOT}/ops/run"
mkdir -p "$MANIFEST_DIR"

echo "$CANDIDATE_PID" > "$PIDFILE"
echo "PID written to pidfile: $PIDFILE"

TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

cat > "$CAPTURE_FILE" <<CAPTURE_EOF
# Current Production PID Capture
# Generated by prod_capture_pid.sh
# Timestamp: $TIMESTAMP
# Operator note: capture only, no stop/kill

PID=$CANDIDATE_PID
EXE_PATH=$EXE_PATH
CMDLINE=$CMDLINE
MODEL_PATH_MATCH=YES
PORT_MATCH=$EXPECTED_PORT
HOST_MATCH=$EXPECTED_HOST
VERIFICATION_RESULT=PASSED
OPERATOR_NOTE=capture only, no stop/kill
ALLOW_CAPTURE_CURRENT_PROD_PID=YES
CAPTURE_EOF

echo "Capture manifest written to: $CAPTURE_FILE"
echo ""
echo "=== PID capture complete ==="
echo "PID: $CANDIDATE_PID"
echo "Pidfile: $PIDFILE"
echo "Manifest: $CAPTURE_FILE"